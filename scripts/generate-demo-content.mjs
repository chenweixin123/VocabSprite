const makeSense = (word, packId, index) => {
  const [
    lemma,
    partOfSpeech,
    senseKey,
    definitionZh,
    definitionEn,
    example,
    translation,
    collocation,
  ] = word;
  const key = identity(word);
  const cueBase = `${lemma}：${definitionZh}`;
  return {
    id: stableId('sense', key),
    identityKey: key,
    lexemeId: stableId('lexeme', normalize(lemma)),
    lemma,
    partOfSpeech,
    senseKey,
    definitionZh,
    definitionEn,
    examples: [
      {
        id: stableId('example', `${key}:original`),
        text: example,
        translation,
        source: 'original',
      },
    ],
    collocations: [collocation],
    synonyms: [],
    antonyms: [],
    confusables: confusion[lemma] ?? [],
    morphology: [`${lemma} · ${partOfSpeech}`],
    cues: [
      {
        id: stableId('cue', `${key}:visual`),
        type: 'visual',
        text: `把“${cueBase}”放进一个清晰的小场景中。`,
        verified: true,
      },
      {
        id: stableId('cue', `${key}:morphology`),
        type: 'morphology',
        text: `先确认词形 ${lemma}，再连接核心义“${definitionZh}”。`,
        verified: true,
      },
      ...(confusion[lemma]?.length
        ? [
            {
              id: stableId('cue', `${key}:contrast`),
              type: 'contrast',
              text: `与 ${confusion[lemma].join(' / ')} 对照：先看词性和句中作用。`,
              verified: true,
            },
          ]
        : []),
    ],
    motion: {
      kind: motions[index % motions.length],
      intensity: index % 3 === 0 ? 'standard' : 'low',
      durationMs: 520 + (index % 4) * 100,
      iterationCount: 1,
    },
    ...(visualKeys.has(key) ? { visualAssetId: visualKeys.get(key) } : {}),
  };
};


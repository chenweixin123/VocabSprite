const normalize = (value) =>
  value.normalize('NFKC').trim().toLowerCase().replaceAll(/\s+/g, ' ');
const identity = (word) => `${normalize(word[0])}|${word[1]}|${normalize(word[2])}`;
const stableId = (namespace, key) => {
  let high = 0x811c9dc5;
  let low = 0x01000193;
  for (const character of `${namespace}:${key}`) {
    const code = character.codePointAt(0) ?? 0;
    high = Math.imul(high ^ code, 0x01000193) >>> 0;
    low = Math.imul(low ^ (code >>> 8), 0x85ebca6b) >>> 0;
  }
  return `${namespace}.${high.toString(16).padStart(8, '0')}${low.toString(16).padStart(8, '0')}`;
};
const canonical = (value) => `${JSON.stringify(value, null, 2)}\n`;
const sha = (value) =>
  `sha256:${createHash('sha256').update(canonical(value), 'utf8').digest('hex')}`;

